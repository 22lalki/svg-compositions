const sizeOf = ([width, height]: [number, number]) => ({ width, height })

export const BUILTIN_ITEMS: Item[] = Object.entries(META).map(([id, meta]) => {
  const dims = SET.items[id]
  if (!dims) throw new Error(`В наборе нет объекта ${id}`)
  return {
    id,
    ...meta,
    builtin: true,
    variants: {
      'L-main': sizeOf(dims.L),
      'L-bg': sizeOf(dims.L),
      'S-main': sizeOf(dims.S),
      'S-bg': sizeOf(dims.S),
    },
  }
})

/** Размер варианта; если нужного состояния нет (у загруженного объекта), берем другой — для рамок и раскладки */
export function itemSize(item: Item, size: SizeKey, state: ObjState): { width: number; height: number } | null {
  return item.variants[variantKey(size, state)] ?? item.variants[variantKey(size, state === 'bg' ? 'main' : 'bg')] ?? null
}
