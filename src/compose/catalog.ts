import { SET, type ObjState, type SizeKey } from './model'

/**
 * Объект набора: встроенный (public/set) или загруженный пользователем.
 * names — как объект называют (сценарий «по названиям»), keywords — с чем он ассоциируется (сценарий «по метафоре»).
 */
export type Item = {
  id: string
  name: string
  names: string[]
  keywords: string[]
  /** С чем объект хорошо смотрится в паре: дополняет композицию, если по метафоре нашелся один объект */
  related: string[]
  builtin: boolean
  /** Размеры вариантов; варианта может не быть у загруженного объекта */
  variants: Partial<Record<VariantKey, { width: number; height: number }>>
  createdAt?: number
}

export type VariantKey = `${SizeKey}-${ObjState}`
export const variantKey = (size: SizeKey, state: ObjState): VariantKey => `${size}-${state}`

